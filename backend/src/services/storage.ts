import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';

import type { Env } from '../config/env.js';

export interface StoredFile {
  body: Buffer;
  contentType: string;
}

/** Private object storage. Files are only ever served through authorised API routes. */
export interface Storage {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<StoredFile | null>;
  delete(key: string): Promise<void>;
}

/** Development driver: files on local disk, content type kept in a sidecar. */
export class LocalStorage implements Storage {
  constructor(private readonly root: string) {}

  private resolve(key: string): string {
    // Keys are generated by us, but guard against traversal anyway.
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error('Invalid storage key');
    return full;
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    const file = this.resolve(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body);
    await writeFile(`${file}.meta`, contentType);
  }

  async get(key: string): Promise<StoredFile | null> {
    const file = this.resolve(key);
    try {
      const [body, contentType] = await Promise.all([readFile(file), readFile(`${file}.meta`, 'utf8')]);
      return { body, contentType };
    } catch {
      return null;
    }
  }

  async delete(key: string): Promise<void> {
    const file = this.resolve(key);
    await Promise.all([rm(file, { force: true }), rm(`${file}.meta`, { force: true })]);
  }
}

/** S3-compatible driver (Cloudflare R2 in production). */
export class S3Storage implements Storage {
  private readonly client: S3Client;
  constructor(
    private readonly bucket: string,
    config: { endpoint: string; region: string; accessKeyId: string; secretAccessKey: string },
  ) {
    this.client = new S3Client({
      endpoint: config.endpoint,
      region: config.region,
      credentials: { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey },
    });
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: contentType }));
  }

  async get(key: string): Promise<StoredFile | null> {
    try {
      const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      if (!res.Body) return null;
      const bytes = await res.Body.transformToByteArray();
      return { body: Buffer.from(bytes), contentType: res.ContentType ?? 'application/octet-stream' };
    } catch (err) {
      if (err instanceof Error && err.name === 'NoSuchKey') return null;
      throw err;
    }
  }

  async delete(key: string): Promise<void> {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

/** In-memory driver for tests. */
export class MemoryStorage implements Storage {
  readonly files = new Map<string, StoredFile>();
  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    this.files.set(key, { body, contentType });
  }
  async get(key: string): Promise<StoredFile | null> {
    return this.files.get(key) ?? null;
  }
  async delete(key: string): Promise<void> {
    this.files.delete(key);
  }
}

export function createStorage(env: Env): Storage {
  if (env.STORAGE_DRIVER === 's3') {
    return new S3Storage(env.S3_BUCKET!, {
      endpoint: env.S3_ENDPOINT!,
      region: env.S3_REGION,
      accessKeyId: env.S3_ACCESS_KEY_ID!,
      secretAccessKey: env.S3_SECRET_ACCESS_KEY!,
    });
  }
  return new LocalStorage(path.resolve(env.STORAGE_LOCAL_DIR));
}
