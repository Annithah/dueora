#!/usr/bin/env node
/**
 * Keep the production (PostgreSQL) schema and migrations in step with the SQLite
 * development schema (DECISIONS.md D1).
 *
 *   npm run db:pg:migration -- <name>
 *
 * 1. Derives prisma/postgres/schema.prisma from prisma/schema.prisma (provider swap).
 * 2. Diffs the previous Postgres schema against the new one with `prisma migrate diff`
 *    (no database needed) and writes prisma/postgres/migrations/<timestamp>_<name>/.
 *
 * Run it whenever prisma/schema.prisma changes, after `npm run db:migrate`.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'prisma/schema.prisma');
const dir = path.join(root, 'prisma/postgres');
const target = path.join(dir, 'schema.prisma');
const migrations = path.join(dir, 'migrations');
const name = (process.argv[2] ?? 'update').replace(/[^a-z0-9_]+/gi, '_').toLowerCase();

const sqlite = readFileSync(source, 'utf8');
if (!/provider\s*=\s*"sqlite"/.test(sqlite)) throw new Error('Expected the development schema to use provider "sqlite"');
const header = '// GENERATED by scripts/postgres-migration.mjs from ../schema.prisma — do not edit by hand.\n';
const postgres = header + sqlite.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"').replace('output       = "../src/generated/prisma"', 'output       = "../../src/generated/prisma"');

mkdirSync(migrations, { recursive: true });
const previous = existsSync(target) ? path.join(dir, '.previous.prisma') : null;
if (previous) writeFileSync(previous, readFileSync(target, 'utf8'));
writeFileSync(target, postgres);

// Run Prisma's CLI with this Node binary (no shell, works the same on Windows and Linux).
const prismaCli = path.join(root, 'node_modules/prisma/build/index.js');
const args = ['migrate', 'diff', ...(previous ? ['--from-schema', previous] : ['--from-empty']), '--to-schema', target, '--script'];
const sql = execFileSync(process.execPath, [prismaCli, ...args], { cwd: root, encoding: 'utf8' });
if (previous) rmSync(previous);

if (!sql.trim() || /^-- This is an empty migration\.?\s*$/m.test(sql.trim())) {
  console.log('Postgres schema unchanged — no migration written.');
} else {
  const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
  const folder = path.join(migrations, `${stamp}_${name}`);
  mkdirSync(folder, { recursive: true });
  writeFileSync(path.join(folder, 'migration.sql'), sql);
  console.log(`Wrote ${path.relative(root, folder)}/migration.sql`);
}
writeFileSync(path.join(migrations, 'migration_lock.toml'), '# Managed by Prisma Migrate.\nprovider = "postgresql"\n');
